// EAN-13 oder EAN-8 mit richtiger Prüfziffer (Gewichte 3 und 1 von rechts).
export function eanGueltig(ean) {
  if (typeof ean !== "string" || !/^(\d{8}|\d{13})$/.test(ean)) return false;
  const ziffern = [...ean].map(Number);
  const pruef = ziffern.pop();
  const summe = ziffern.reverse().reduce((s, z, i) => s + z * (i % 2 === 0 ? 3 : 1), 0);
  return (10 - (summe % 10)) % 10 === pruef;
}

// Nummer aus dem Scanner oder dem Eingabefeld: Leerzeichen und Striche weg, UPC-A (12 Stellen) mit 0 vorn zu EAN-13.
// Ergebnis ist eine gültige EAN oder null.
export function eanAusEingabe(text) {
  if (typeof text !== "string") return null;
  let ean = text.replace(/[\s-]/g, "");
  if (/^\d{12}$/.test(ean)) ean = `0${ean}`;
  return eanGueltig(ean) ? ean : null;
}

// Sucht eine Nummer zuerst in den eigenen Sorten (Kopie aus der Liste über listeId oder eigene Sorte mit "ean"),
// dann in der Futterliste. { art: "eigene", futter, eintrag? } | { art: "liste", eintrag } | null
export function findeNachEan(ean, eigeneFutter, liste = FUTTERLISTE) {
  const eintrag = liste.find((e) => e.ean?.includes(ean));
  const kopie = eintrag && eigeneFutter.find((f) => f.listeId === eintrag.id);
  if (kopie) return { art: "eigene", futter: kopie, eintrag };
  const eigene = eigeneFutter.find((f) => Array.isArray(f.ean) && f.ean.includes(ean));
  if (eigene) return { art: "eigene", futter: eigene };
  return eintrag ? { art: "liste", eintrag } : null;
}

// Entfernt ungültige Nummern an eigenen Sorten (z. B. aus einer eingelesenen Sicherung); gibt die Anzahl zurück.
export function eanBereinigen(daten) {
  let entfernt = 0;
  for (const futter of daten.futter) {
    if (!("ean" in futter)) continue;
    const gueltig = Array.isArray(futter.ean) ? futter.ean.filter(eanGueltig) : [];
    entfernt += Array.isArray(futter.ean) ? futter.ean.length - gueltig.length : 1;
    if (gueltig.length > 0) futter.ean = gueltig;
    else delete futter.ean;
  }
  return entfernt;
}

// kcal pro 100 g aus den Analytischen Bestandteilen, bei Trockenfutter ohne Feuchte mit der Annahme oben.
export function nachrechnung(eintrag) {
  return kcalAusBestandteilen({ ...eintrag.analyse, feuchte: eintrag.analyse.feuchte ?? FEUCHTE_TROCKEN_ANNAHME });
}

// Findet Einträge, deren Name alle eingegebenen Wörter enthält (Groß-/Kleinschreibung egal).
export function sucheFutter(text, liste = FUTTERLISTE) {
  const woerter = text.toLowerCase().split(/\s+/).filter(Boolean);
  return liste.filter((eintrag) => woerter.every((wort) => eintrag.name.toLowerCase().includes(wort)));
}

// Gruppen im Blatt „Aus der Liste wählen“ (seit 0.69.0, Stefan 06.11.: Leckerlis gingen zwischen 48 Sorten unter):
// Diätfutter bleibt wegen „nur nach Rücksprache“ eine eigene Gruppe, der Rest nach Art. Leere Gruppen fallen weg.
const GRUPPEN = [
  { id: "liste-diaet", titel: "Diätfutter – nur nach tierärztlicher Rücksprache", passt: (e) => e.diaet },
  { id: "liste-nass", titel: "Nassfutter", passt: (e) => !e.diaet && e.typ === "nass" },
  { id: "liste-trocken", titel: "Trockenfutter", passt: (e) => !e.diaet && e.typ === "trocken" },
  { id: "liste-leckerli", titel: "Leckerlis", passt: (e) => !e.diaet && e.typ === "leckerli" },
];
export const LISTEN_GRUPPEN = GRUPPEN.map((g) => g.id);

export function listenGruppen(treffer) {
  return GRUPPEN.map(({ id, titel, passt }) => ({ id, titel, eintraege: treffer.filter(passt) })).filter(
    (g) => g.eintraege.length > 0
  );
}

// kcal aus Futter, das kein Diätfutter der Liste ist (Leckerlis zählen getrennt). Eigene Sorten gelten als normales
// Futter, weil die App bei ihnen nicht weiß, ob es ein Diätfutter ist.
export function normalesFutterKcal(mahlzeiten, futterNachId, liste = FUTTERLISTE) {
  const diaet = new Set(liste.filter((e) => e.diaet).map((e) => e.id));
  let kcal = 0;
  for (const mahlzeit of mahlzeiten) {
    const futter = futterNachId.get(mahlzeit.futterId);
    if (futter && futter.typ !== "leckerli" && !diaet.has(futter.listeId)) kcal += kcalFuer(mahlzeit.gramm, futter.kcalPro100g);
  }
  return kcal;
}

const prozent = (wert) => `${String(wert).replace(".", ",")} %`;

// Eigene Kopie eines Listeneintrags für daten.futter. Quelle und Stand stehen in der Notiz.
export function ausListe(eintrag, id) {
  const { protein, fett, asche, faser, feuchte } = eintrag.analyse;
  const teile = [
    eintrag.diaet ? "Diätfutter – nur nach tierärztlicher Rücksprache." : "",
    `Laut ${eintrag.quelle}: Protein ${prozent(protein)}, Fett ${prozent(fett)}, Asche ${prozent(asche)}, ` +
      `Faser ${prozent(faser)}, Feuchte ${feuchte === null ? "nicht angegeben" : prozent(feuchte)}.`,
    eintrag.kcalQuelle === "geschaetzt"
      ? "Kein kcal-Wert veröffentlicht, aus den Bestandteilen berechnet (NRC 2006)."
      : "",
    eintrag.hinweis,
    `Aus der Kilossos-Futterliste, Stand ${eintrag.abgerufen.split("-").reverse().join(".")}. Bei Abweichung gilt die Packung.`,
  ];
  return {
    id,
    listeId: eintrag.id,
    name: eintrag.name,
    typ: eintrag.typ,
    kcalPro100g: eintrag.kcalPro100g,
    kcalQuelle: eintrag.kcalQuelle,
    notiz: teile.filter(Boolean).join(" "),
  };
}
